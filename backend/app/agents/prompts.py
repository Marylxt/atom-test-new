_FENCE_RE = re.compile(r"```(?:html|HTML|Html)?\s*\n?(.*?)```", re.DOTALL)


def extract_html(raw: str) -> str:
    """从模型输出里稳定地抠出完整 HTML（兼容代码块包裹 / 夹带解释文字）。"""
    text = (raw or "").strip()
    if not text:
        return ""

    # 1) 优先取最长的一段「看起来像 HTML」的代码块（解释性的短代码块会被自动忽略）；
    #    如果通篇没有 HTML 代码块，就保留原文，交给下面的截取逻辑处理。
    blocks = [b.strip() for b in _FENCE_RE.findall(text) if b.strip()]
    html_blocks = [b for b in blocks if "<html" in b.lower() or "<!doctype" in b.lower()]
    if html_blocks:
        text = max(html_blocks, key=len)

    # 2) 截掉 HTML 前后的解释性文字
    lowered = text.lower()
    start = lowered.find("<!doctype")
    if start == -1:
        start = lowered.find("<html")
    end = lowered.rfind("</html>")
    if start != -1 and end != -1:
        text = text[start : end + len("</html>")]
    elif start != -1:
        text = text[start:]

    return text.strip()


def looks_like_html(text: str) -> bool:
    """粗校验：产物是否是一份可运行的 HTML。"""
    if not text:
        return False
    lowered = text.lower()
    return "<html" in lowered and "</html>" in lowered and "<body" in lowered


def content_to_text(message) -> str:
    """把 LangChain 的消息/分片统一转成纯文本。

    兼容三种情况：`content` 是 str、是 `[{type: text, text: ...}]` 之类的分片数组、
    或者直接传进来一个字符串。
    """
    content = getattr(message, "content", message)
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts: list[str] = []
        for item in content:
            if isinstance(item, str):
                parts.append(item)
            elif isinstance(item, dict) and item.get("type") in {"text", "text_delta"}:
                parts.append(str(item.get("text", "")))
        return "".join(parts)
    return ""
